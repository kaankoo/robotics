// Cycle detection (DAG validation)
function checkCycles(edges) {
  const visited = new Set();
  const recStack = new Set();

  function dfs(node, path) {
    visited.add(node);
    recStack.add(node);

    const upstreams = edges[node] || [];
    for (const neighbor of upstreams) {
      if (!visited.has(neighbor)) {
        if (dfs(neighbor, [...path, neighbor])) return true;
      } else if (recStack.has(neighbor)) {
        console.error(`CYCLE DETECTED: ${[...path, neighbor].join(" -> ")}`);
        return true;
      }
    }
    recStack.delete(node);
    return false;
  }

  for (const node of Object.keys(edges)) {
    if (!visited.has(node)) {
      if (dfs(node, [node])) return true;
    }
  }
  return false;
}

