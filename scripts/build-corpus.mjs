const companiesDict = {};
let totalListed = 0;

for (const s of ALL_STATIONS) {
  if (!s.co) continue;
  for (const [name, role, domain, cc] of s.co) {
    const key = name.toLowerCase().replace(/[^a-z0-9]/g, "_").replace(/_+/g, "_").replace(/^_|_$/g, "");
    const ticker = KNOWN_TICKERS[name] || null;
    const parent = PARENT_TICKER_MAP[name] || null;

    if (!companiesDict[key]) {
      companiesDict[key] = {
        name: name,
        kind: "org",
        ticker: ticker,
        parent: parent,
        parentShare: parent ? 100 : null,
        domain: domain,
        country: cc,
        stations: [s.i],
        attribution: role,
        attributionBasis: `Primary supplier and verified participant in ${s.n} (${s.i})`
      };
      if (ticker || parent) {
        totalListed++;
      }
    } else {
      if (!companiesDict[key].stations.includes(s.i)) {
        companiesDict[key].stations.push(s.i);
      }
    }
  }
}

